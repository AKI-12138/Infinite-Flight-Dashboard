// メニューを閉じるときにフォーカスをトリガー（開くのに押したボタン）へ戻す共通処理。
//
// ⚠️ **順番が肝**。ドロップダウンの中身は、閉じると `display:none` になるか DOM から消える。
//    項目にフォーカスが載ったまま閉じると、その要素ごと消えてブラウザがフォーカスを `body` へ落とす。
//    見た目には何も起きないが、**キーボード利用者は現在位置を失い、次の Tab がページ先頭から
//    始まり直す**（ADV-010 の Codex 再確認で Jump メニューにて実ブラウザ再現）。
//    先にトリガーへ移してから閉じれば、`body` へ落ちる瞬間そのものが起きない。
//
// ⚠️ **呼ぶのは「閉じる意思のある操作」だけ**＝Escape／メニュー項目の選択。
//    **外側クリックでは呼ばない**。押した先の要素が自然にフォーカスを受け取るので、
//    そこから奪い返すと「クリックしたものが効かない」別の不具合になる。
//
// ⚠️ メニュー項目からモーダルを開く場合も、これを**先に**通すこと。
//    `focus-trap.ts` は「開いた瞬間の `document.activeElement`」を復帰先として覚えるので、
//    その時点でフォーカスが `body` に落ちていると、モーダルを閉じても戻る先が無くなる。
//    先にトリガーへ戻しておけば、モーダルを閉じたときそのボタンへ自然に返ってくる。
export function closeMenuRestoringFocus(
  trigger: HTMLElement | null | undefined,
  close: () => void,
): void {
  // preventScroll：トリガーは常に画面内（ヘッダ／貼り付きバー）にあり表示は動かないが、
  // 直後のスクロール処理と競合させないため明示する。
  trigger?.focus({ preventScroll: true });
  close();
}
